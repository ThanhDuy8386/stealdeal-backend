#!/usr/bin/env bash

set -Eeuo pipefail
umask 077

readonly AWS_REGION="${AWS_REGION:-us-east-1}"
readonly PARAMETER_PATH="${PARAMETER_PATH:-/stealdeal/prod}"
readonly ENV_FILE="${BACKEND_ENV_FILE:-/opt/stealdeal/config/backend.env}"
readonly CONFIG_DIR="$(dirname -- "$ENV_FILE")"
readonly LOCK_FILE="${BACKEND_SECRETS_LOCK_FILE:-${CONFIG_DIR}/.sync-backend-secrets.lock}"

readonly REQUIRED_KEYS=(
  JWT_SECRET
  AWS_ACCESS_KEY
  AWS_SECRET_KEY
  BREVO_API_KEY
  GEOAPIFY_API_KEY
  VNPAY_TMN_CODE
  VNPAY_HASH_SECRET
  MSSQL_SA_PASSWORD
)

temporary_env_file=""
temporary_rows_file=""

log() {
  printf '%s\n' "$*" >&2
}

cleanup() {
  if [[ -n "$temporary_env_file" ]]; then
    rm -f -- "$temporary_env_file"
  fi

  if [[ -n "$temporary_rows_file" ]]; then
    rm -f -- "$temporary_rows_file"
  fi
}

fail() {
  log "Secret synchronization failed: $*"
  exit 1
}

require_command() {
  command -v "$1" >/dev/null 2>&1 || fail "required command '$1' is not installed"
}

dotenv_quote() {
  local value="$1"

  # Compose treats single-quoted dotenv values literally. Escape the two
  # characters that can affect the surrounding single-quoted value.
  value="${value//\\/\\\\}"
  value="${value//\'/\\\'}"
  printf "'%s'" "$value"
}

trap cleanup EXIT

if [[ "${EUID}" -ne 0 ]]; then
  fail "run this script as root"
fi

if [[ "$PARAMETER_PATH" != /* || "$PARAMETER_PATH" == */ ]]; then
  fail "PARAMETER_PATH must start with '/' and must not end with '/'"
fi

require_command aws
require_command jq
require_command flock

install -d -o root -g root -m 700 -- "$CONFIG_DIR"

if [[ ! -d "$(dirname -- "$LOCK_FILE")" ]]; then
  fail "lock file directory does not exist"
fi

exec 9>"$LOCK_FILE"
flock -n 9 || fail "another secret synchronization is already running"

temporary_env_file="$(mktemp "${ENV_FILE}.tmp.XXXXXX")"
temporary_rows_file="$(mktemp "${ENV_FILE}.rows.XXXXXX")"

expected_keys_json="$({ printf '%s\n' "${REQUIRED_KEYS[@]}"; } | jq -R . | jq -s .)"

if ! AWS_PAGER="" aws ssm get-parameters-by-path \
  --region "$AWS_REGION" \
  --path "$PARAMETER_PATH" \
  --recursive \
  --with-decryption \
  --output json \
  | jq -er \
      --arg path "$PARAMETER_PATH" \
      --argjson expected_keys "$expected_keys_json" \
      '
        if (.Parameters | type) != "array" then
          error("Parameter Store response does not contain a Parameters array")
        else
          .Parameters as $parameters
          | ($expected_keys | map($path + "/" + .) | sort) as $expected_names
          | ($parameters | map(.Name) | sort) as $actual_names
          | if $actual_names != $expected_names then
              error("Parameter Store path does not contain exactly the required parameters")
            elif any($parameters[]; .Type != "SecureString") then
              error("Every required parameter must use SecureString")
            elif any($parameters[]; (.Value | type) != "string" or (.Value | test("\\S") | not)) then
              error("A required parameter has an empty value")
            elif any(
              $parameters[];
              (.Value | explode | any(.[]; . == 0 or . == 10 or . == 13))
            ) then
              error("Parameter values must not contain NUL, CR, or LF")
            else
              $expected_keys[] as $key
              | ($parameters[] | select(.Name == ($path + "/" + $key))) as $parameter
              | [$key, ($parameter.Value | @base64)]
              | @tsv
            end
        end
      ' >"$temporary_rows_file"; then
  fail "could not retrieve and validate Parameter Store values"
fi

{
  printf '%s\n' '# Generated by sync-backend-secrets.sh. Do not edit.'
  printf '%s\n' 'ASPNETCORE_ENVIRONMENT=Production'

  while IFS=$'\t' read -r key encoded_value; do
    [[ -n "$key" && -n "$encoded_value" ]] || fail "invalid validated parameter row"

    value="$(printf '%s' "$encoded_value" | jq -Rr '@base64d')"
    printf '%s=%s\n' "$key" "$(dotenv_quote "$value")"
  done <"$temporary_rows_file"
} >"$temporary_env_file"

actual_key_count="$(grep -Ec '^(JWT_SECRET|AWS_ACCESS_KEY|AWS_SECRET_KEY|BREVO_API_KEY|GEOAPIFY_API_KEY|VNPAY_TMN_CODE|VNPAY_HASH_SECRET|MSSQL_SA_PASSWORD)=' "$temporary_env_file")"
if [[ "$actual_key_count" -ne "${#REQUIRED_KEYS[@]}" ]]; then
  fail "generated environment file does not contain all required keys"
fi

chown root:root -- "$temporary_env_file"
chmod 600 -- "$temporary_env_file"
mv -f -- "$temporary_env_file" "$ENV_FILE"
temporary_env_file=""

rm -f -- "$temporary_rows_file"
temporary_rows_file=""

log "Backend secrets synchronized successfully."
